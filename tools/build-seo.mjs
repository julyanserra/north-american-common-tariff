// Builds what search engines and AI assistants read, from the two source pages and i18n.js.
//   node tools/build-seo.mjs        (run it after changing index.html, foundations.html or i18n.js)
//
// Writes:
//   es/index.html, es/fundamentos.html   the Spanish pages as static HTML (crawlers don't run JavaScript)
//   <script id="ld"> in all four pages   structured data (schema.org JSON-LD) read from each page
//   <tbody id="fs-rows"> in Foundations  the fact sheet, prerendered (the script re-renders it)
//   assets/data/*.csv                    the fact sheet as CSV, English and Spanish
//   sitemap.xml                          all four pages with their language alternates
//   llms.txt, llms-full.txt, es/llms-full.txt   plain-text summaries for AI assistants
import { createServer } from "node:http";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { extname, join, normalize, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import vm from "node:vm";

// Playwright is loaded with require so a globally installed copy also works.
const { chromium } = createRequire(import.meta.url)("playwright");

const root = fileURLToPath(new URL("..", import.meta.url));
const SITE = "https://onenorthamerica.org/";
const TODAY = new Date().toISOString().slice(0, 10);
const PUBLISHED = execSync("git log --reverse --format=%ad --date=short", { cwd: root }).toString().split("\n")[0] || TODAY;

const PAGES = [
  { key: "home", en: "index.html", enUrl: "", es: "es/index.html", esUrl: "es/" },
  { key: "foundations", en: "foundations.html", enUrl: "foundations.html", es: "es/fundamentos.html", esUrl: "es/fundamentos.html" },
];

const sandbox = { window: {} };
vm.runInNewContext(await readFile(join(root, "assets/js/i18n.js"), "utf8"), sandbox);
const ES = sandbox.window.I18N.es;

// A tiny static server, so the pages load their own scripts.
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml", ".json": "application/json" };
const server = createServer(async (req, res) => {
  let path = normalize(decodeURIComponent(new URL(req.url, "http://x").pathname)).replace(/^(\.\.[/\\])+/, "");
  if (path.endsWith("/")) path += "index.html";
  try {
    const body = await readFile(join(root, path));
    res.writeHead(200, { "content-type": TYPES[extname(path)] || "application/octet-stream" });
    res.end(body);
  } catch {
    res.writeHead(404); res.end();
  }
}).listen(0);
const base = `http://localhost:${server.address().port}/`;

const browser = await chromium.launch();
// Without scripts: the page exactly as a crawler receives it.
const staticCtx = await browser.newContext({ locale: "en-US" });
await staticCtx.route("**/*", (route) => {
  const r = route.request();
  return r.url().startsWith(base) && r.resourceType() === "document" ? route.continue() : route.abort();
});
// With scripts: to read what the page builds (the fact sheet).
const liveCtx = await browser.newContext({ locale: "en-US" });
await liveCtx.route("**/*", (route) => (route.request().url().startsWith(base) ? route.continue() : route.abort()));

async function openStatic(file) {
  const page = await staticCtx.newPage();
  await page.goto(base + file, { waitUntil: "domcontentloaded" });
  return page;
}
const read = (file) => readFile(join(root, file), "utf8");
async function write(file, text) {
  await mkdir(dirname(join(root, file)), { recursive: true });
  await writeFile(join(root, file), text);
  console.log("wrote", file);
}
const HEADER = "<!doctype html>\n<!-- Generated by tools/build-seo.mjs from the English page and assets/js/i18n.js. Edit those, then rebuild. -->\n";

/* ───────── 1. The Spanish pages ───────── */
for (const pg of PAGES) {
  const page = await openStatic(pg.en);
  const missing = await page.evaluate(({ es, pg, site }) => {
    const d = document;
    const missing = [];
    d.documentElement.lang = "es";
    d.querySelectorAll("[data-i18n],[data-i18n-html]").forEach((n) => {
      const k = n.getAttribute("data-i18n") || n.getAttribute("data-i18n-html");
      if (es[k] != null) n.innerHTML = es[k]; else missing.push(k);
    });
    const set = (sel, attr, val) => { const n = d.querySelector(sel); if (n && val) n.setAttribute(attr, val); };
    d.title = es["meta.title." + pg.key];
    set('meta[name="description"]', "content", es["meta.desc." + pg.key]);
    set('meta[property="og:title"]', "content", es["meta.ogt." + pg.key]);
    set('meta[name="twitter:title"]', "content", es["meta.ogt." + pg.key]);
    set('meta[property="og:description"]', "content", es["meta.og." + pg.key]);
    set('meta[name="twitter:description"]', "content", es["meta.og." + pg.key]);
    set('meta[property="og:url"]', "content", site + pg.esUrl);
    set('link[rel="canonical"]', "href", site + pg.esUrl);
    set('meta[property="og:locale"]', "content", "es_MX");
    set('meta[property="og:locale:alternate"]', "content", "en_US");
    // The Spanish pages sit one folder down; the Spanish Foundations page has a Spanish name.
    d.querySelectorAll("[href],[src]").forEach((n) => {
      ["href", "src"].forEach((a) => {
        const v = n.getAttribute(a);
        if (!v) return;
        if (/^assets\//.test(v)) n.setAttribute(a, "../" + v);
        else if (/^foundations\.html/.test(v)) n.setAttribute(a, v.replace(/^foundations\.html/, "fundamentos.html"));
      });
    });
    d.querySelectorAll(".lang button").forEach((b) => {
      const es = b.dataset.lang === "es";
      b.setAttribute("aria-pressed", String(es));
      if (es) b.removeAttribute("data-href"); else b.setAttribute("data-href", "../" + pg.enUrl);
    });
    return missing;
  }, { es: ES, pg, site: SITE });
  if (missing.length) console.warn(`  ${pg.en}: no Spanish for ${missing.length} keys: ${[...new Set(missing)].join(", ")}`);
  await write(pg.es, HEADER + (await page.evaluate(() => document.documentElement.outerHTML)) + "\n");
  await page.close();
}

/* ───────── 2. The fact sheet, prerendered, and as CSV ───────── */
const csv = {};
for (const [file, lang] of [["foundations.html", "en"], ["es/fundamentos.html", "es"]]) {
  const page = await liveCtx.newPage();
  await page.goto(base + file, { waitUntil: "load" });
  await page.waitForSelector("#fs-rows tr");
  const sheet = await page.evaluate(() => {
    const cells = (tr) => [...tr.children].map((td) => td.textContent.replace(/\s*↗$/, "").trim());
    return {
      rows: document.querySelector("#fs-rows").innerHTML,
      head: [...document.querySelectorAll(".fs-table th")].map((th) => th.textContent.trim()),
      data: [...document.querySelectorAll("#fs-rows tr")].map((tr) => cells(tr).concat((tr.querySelector(".fs-src a") || {}).href || "")),
    };
  });
  await page.close();
  const text = await read(file);
  await writeFile(join(root, file), text.replace(/<tbody id="fs-rows">[\s\S]*?<\/tbody>/, `<tbody id="fs-rows">${sheet.rows}</tbody>`));
  const cell = (v) => '"' + String(v).replace(/"/g, '""') + '"';
  csv[lang] = "﻿" + [sheet.head.concat("URL")].concat(sheet.data).map((r) => r.map(cell).join(",")).join("\r\n") + "\r\n";
}
const CSV_FILE = { en: "assets/data/one-north-america-fact-sheet.csv", es: "assets/data/una-norteamerica-cifras.csv" };
await write(CSV_FILE.en, csv.en);
await write(CSV_FILE.es, csv.es);

/* ───────── 3. Structured data and plain text, read from each page ───────── */
function buildLd({ pg, lang, site, today, published, csvUrl }) {
  const d = document;
  const txt = (n) => (n ? n.textContent.replace(/\s+/g, " ").trim() : "");
  const meta = (sel) => (d.querySelector(sel) || {}).content || "";
  const es = lang === "es";
  const url = site + (es ? pg.esUrl : pg.enUrl);
  const id = (frag) => url + "#" + frag;
  const graph = [];
  const org = { "@type": "Organization", "@id": site + "#sai", name: "SAI Derecho & Economía", alternateName: "SAI Law & Economics", url: "https://sai.com.mx/" };
  const paper = {
    "@type": "ScholarlyArticle", "@id": site + "#noyola-serra-2025",
    name: "A Case for a North American Common Tariff",
    author: [{ "@type": "Person", name: "Pedro Noyola" }, { "@type": "Person", name: "Jaime Serra Puche" }],
    datePublished: "2025", publisher: { "@type": "Organization", name: "Wilson Center, Mexico Institute" },
    url: "https://www.wilsoncenter.org/article/case-north-american-common-tariff",
  };
  const about = [
    { "@type": "Thing", name: es ? "Unión aduanera de América del Norte" : "North American customs union" },
    { "@type": "Thing", name: es ? "Arancel externo común" : "Common external tariff" },
    { "@type": "Thing", name: es ? "T-MEC" : "USMCA" },
    { "@type": "Place", name: es ? "América del Norte" : "North America" },
  ];
  const image = meta('meta[property="og:image"]');
  graph.push(org, paper, {
    "@type": "WebSite", "@id": site + "#website", url: site, name: "One North America", alternateName: "Una Norteamérica",
    inLanguage: ["en", "es"], publisher: { "@id": org["@id"] },
  });
  const webpage = {
    "@type": "WebPage", "@id": id("webpage"), url, name: d.title, description: meta('meta[name="description"]'),
    inLanguage: lang, isPartOf: { "@id": site + "#website" }, publisher: { "@id": org["@id"] },
    primaryImageOfPage: { "@type": "ImageObject", url: image, width: 1200, height: 630 },
    datePublished: published, dateModified: today, about, isBasedOn: { "@id": paper["@id"] },
  };
  graph.push(webpage);

  // Questions and answers: the FAQ on the vision page, the objections on Foundations.
  const qa = pg.key === "home"
    ? [...d.querySelectorAll(".qa details")].map((q) => [txt(q.querySelector("summary")), txt(q.querySelector("p"))])
    : [...d.querySelectorAll("#questions .oq")].map((q) => { const p = q.querySelectorAll("p:not(.oq-k):not(.src)"); return [txt(q.querySelector("h3")), txt(p[p.length - 1])]; });
  if (qa.length) graph.push({
    "@type": "FAQPage", "@id": id(pg.key === "home" ? "faq" : "questions"), url: id(pg.key === "home" ? "faq" : "questions"),
    inLanguage: lang, isPartOf: { "@id": webpage["@id"] },
    mainEntity: qa.map(([q, a]) => ({ "@type": "Question", name: q, acceptedAnswer: { "@type": "Answer", text: a } })),
  });

  if (pg.key === "foundations") {
    const home = site + (es ? "es/" : "");
    graph.push({
      "@type": "BreadcrumbList", "@id": id("breadcrumbs"),
      itemListElement: [
        { "@type": "ListItem", position: 1, name: es ? "Una Norteamérica" : "One North America", item: home },
        { "@type": "ListItem", position: 2, name: es ? "Fundamentos" : "Foundations", item: url },
      ],
    });
    webpage.breadcrumb = { "@id": id("breadcrumbs") };
    const terms = [...d.querySelectorAll(".glossary .method")].map((m) => ({
      "@type": "DefinedTerm", "@id": id(m.id), url: id(m.id), name: txt(m.querySelector("dfn")), description: txt(m.querySelector("dd")),
      inDefinedTermSet: { "@id": id("terms") },
    }));
    graph.push({ "@type": "DefinedTermSet", "@id": id("terms"), url: id("terms"), name: txt(d.querySelector("#gl-title")), inLanguage: lang, hasDefinedTerm: terms });
    webpage.about = terms.map((t) => ({ "@id": t["@id"] }));
    graph.push({
      "@type": "Article", "@id": id("article"), mainEntityOfPage: { "@id": webpage["@id"] },
      headline: txt(d.querySelector("h1")), description: meta('meta[name="description"]'), inLanguage: lang, image,
      author: { "@id": org["@id"] }, publisher: { "@id": org["@id"] }, datePublished: published, dateModified: today,
      isBasedOn: { "@id": paper["@id"] }, about: terms.map((t) => ({ "@id": t["@id"] })),
      citation: [...d.querySelectorAll(".biblio li")].map((li) => txt(li).replace(/\s*\S+\s↗$/, "")),
    });
    graph.push({
      "@type": "Dataset", "@id": id("facts"), url: id("facts"), name: (es ? "Una Norteamérica: cifras y fuentes" : "One North America: figures and sources"),
      description: es
        ? "Cada cifra del sitio Una Norteamérica sobre una unión aduanera de América del Norte (comercio, aranceles, inversión, energía, demografía), con su valor, su fuente y un enlace a ella."
        : "Every figure on the One North America site about a North American customs union (trade, tariffs, investment, energy, demography), with its value, its source and a link to it.",
      inLanguage: lang, creator: { "@id": org["@id"] }, isAccessibleForFree: true, spatialCoverage: { "@type": "Place", name: es ? "América del Norte" : "North America" },
      temporalCoverage: "1950/2050", dateModified: today,
      keywords: es ? ["unión aduanera", "arancel externo común", "T-MEC", "comercio México Estados Unidos", "América del Norte"] : ["customs union", "common external tariff", "USMCA", "U.S.-Mexico trade", "North America"],
      distribution: { "@type": "DataDownload", encodingFormat: "text/csv", contentUrl: site + csvUrl },
    });
  }
  return JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 1);
}

// Plain text for AI assistants: headings, paragraphs, lists, Q&A and tables, in reading order.
function toText({ url }) {
  const BLOCK = "h1,h2,h3,h4,p,li,dt,dd,summary,tr,blockquote";
  const SKIP = '[aria-hidden="true"],svg,canvas,script,style,button,nav,.sprite,.skip,.fs-tools,label';
  const norm = (s) => s.replace(/\s+/g, " ").trim();
  const inline = (n) => {
    let s = "";
    n.childNodes.forEach((c) => {
      if (c.nodeType === 3) s += c.textContent;
      else if (c.nodeType === 1 && !c.matches(SKIP)) {
        const inner = norm(inline(c));
        if (c.tagName === "A" && /^https?:/.test(c.getAttribute("href") || "")) s += ` [${inner.replace(/\s*↗$/, "")}](${c.href})`;
        else if (c.tagName === "S") s += ` ~~${inner}~~ `;
        else if (c.tagName === "TD" || c.tagName === "TH") s += inner + " | ";
        else s += " " + inline(c) + " ";
      }
    });
    return s;
  };
  const out = [`Source: ${url}`];
  const roots = [document.querySelector("main"), ...document.querySelectorAll("footer .foot-note")];
  roots.forEach((r) => r.querySelectorAll(BLOCK).forEach((n) => {
    if (n.closest(SKIP) || n.querySelector(BLOCK)) return;
    let t = norm(inline(n)).replace(/\s+([,.;:!?)])/g, "$1").replace(/\(\s+/g, "(");
    if (!t) return;
    const tag = n.tagName;
    if (/^H[1-4]$/.test(tag)) t = "#".repeat(+tag[1]) + " " + t;
    else if (tag === "SUMMARY" || tag === "DT") t = "**" + t + "**";
    else if (tag === "TR") t = "| " + t.replace(/\s*\|\s*$/, "") + " |";
    else if (tag === "LI") t = "- " + t;
    out.push(t);
  }));
  return out.join("\n\n").replace(/(\|[^\n]*)\n\n(?=\|)/g, "$1\n") + "\n";
}

const texts = { en: [], es: [] };
let glossary = [];
let sourceCount = 0;
for (const pg of PAGES) {
  for (const lang of ["en", "es"]) {
    const file = lang === "es" ? pg.es : pg.en;
    const page = await openStatic(file);
    const url = SITE + (lang === "es" ? pg.esUrl : pg.enUrl);
    const ld = await page.evaluate(buildLd, { pg, lang, site: SITE, today: TODAY, published: PUBLISHED, csvUrl: CSV_FILE[lang] });
    texts[lang].push(await page.evaluate(toText, { url }));
    if (pg.key === "foundations" && lang === "en") {
      glossary = await page.evaluate(() => [...document.querySelectorAll(".glossary .method")].map((m) => [m.querySelector("dfn").textContent.trim(), m.id, m.querySelector("dd").textContent.replace(/\s+/g, " ").trim()]));
      sourceCount = await page.evaluate(() => document.querySelectorAll(".biblio li").length);
    }
    await page.close();
    const html = await read(file);
    const re = /(<script type="application\/ld\+json" id="ld">)[\s\S]*?(<\/script>)/;
    if (!re.test(html)) throw new Error(`${file}: no <script id="ld"> to fill`);
    await writeFile(join(root, file), html.replace(re, (m, a, b) => a + "\n" + ld.replace(/<\//g, "<\\/") + "\n  " + b));
    console.log("structured data:", file);
  }
}

